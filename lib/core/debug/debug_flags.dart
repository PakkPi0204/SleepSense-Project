/// Flag สำหรับโหมดทดสอบระหว่างพัฒนา — เก็บใน memory เท่านั้น
/// (รีเซ็ตกลับเป็นค่าเริ่มต้นทุกครั้งที่เปิดแอปใหม่ ไม่ persist)
abstract final class DebugFlags {
  /// ปกติ (false): critical alert ที่ "ค้างอยู่แล้ว" ตอนเปิดแอปครั้งแรกจะไม่เด้ง popup
  /// — เด้งเฉพาะ critical alert ใหม่ที่โผล่มาระหว่างใช้งาน (กันสแปมทุกครั้งที่เปิดแอป)
  ///
  /// โหมดทดสอบ (true): เด้ง popup ให้ critical alert ทุกตัวที่เจอ แม้จะเป็นตัวที่
  /// มีอยู่แล้วตั้งแต่เปิดแอป — มีประโยชน์ตอนทดสอบว่า popup แสดงผลถูกต้องหรือไม่
  /// โดยไม่ต้องรอ sensor ส่งค่าใหม่เข้ามา
  static bool alwaysShowCriticalOnLoad = false;
}
